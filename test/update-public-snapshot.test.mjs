test('fails cleanly on network, redirect, status, MIME and missing-body errors', async () => {
  const variants = [
    () => { throw new Error('network failed with secret internal details'); },
    () => new Response('redirect', { status: 302, headers: { Location: 'https://other.example/' } }),
    () => new Response('not found', { status: 404 }),
    () => new Response('denied', { status: 401 }),
    () => new Response('partial', { status: 206 }),
    () => new Response('html', { headers: { 'Content-Type': 'application/json' } }),
    () => new Response(null, { headers: { 'Content-Type': 'text/html' } }),
    () => { const response = new Response('', { headers: { 'Content-Type': 'text/html' } }); Object.defineProperty(response, 'redirected', { value: true }); return response; },
    () => { const response = new Response('', { headers: { 'Content-Type': 'text/html' } }); Object.defineProperty(response, 'url', { value: 'https://other.example/' }); return response; }
  ];
  for (const variant of variants) {
    const f = fixture();
    f.onRequest = variant;
    await assert.rejects(capture(f), error => {
      assert.match(error.message, /Public snapshot:/);
      assert.doesNotMatch(error.message, /secret internal details/);
      return true;
    });
  }
});

test('bounds advertised and streamed response bytes and rejects invalid UTF-8', async () => {
  for (const response of [
    new Response('small', { headers: { 'Content-Type': 'text/html', 'Content-Length': '999999999' } }),
    new Response(' '.repeat(1024 * 1024 + 1), { headers: { 'Content-Type': 'text/html' } }),
    new Response(Uint8Array.of(0xff), { headers: { 'Content-Type': 'text/html' } })
  ]) {
    const f = fixture();
    f.onRequest = () => response;
    await assert.rejects(capture(f), /size limit|invalid UTF-8/);
  }
});

test('times out an unresponsive fetch and aborts the request', async t => {
  t.mock.timers.enable({ apis: ['setTimeout'] });
  let signal;
  const promise = fetchPublicSnapshot(SITE, { fetchImpl: (_url, init) => {
    signal = init.signal;
    return new Promise(() => {});
  } });
  const rejection = assert.rejects(promise, /request timed out/);
  t.mock.timers.tick(10_000);
  await rejection;
  assert.equal(signal.aborted, true);
});

test('times out a response body that stalls after the headers', async t => {
  t.mock.timers.enable({ apis: ['setTimeout'] });
  let signal;
  const promise = fetchPublicSnapshot(SITE, { fetchImpl: async (_url, init) => {
    signal = init.signal;
    return new Response(new ReadableStream({ start() {} }), { headers: { 'Content-Type': 'text/html' } });
  } });
  const rejection = assert.rejects(promise, /request timed out/);
  await Promise.resolve();
  t.mock.timers.tick(10_000);
  await rejection;
  assert.equal(signal.aborted, true);
});

