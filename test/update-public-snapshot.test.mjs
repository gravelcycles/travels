import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { fetchPublicSnapshot } from '../scripts/update-public-snapshot.mjs';

const SITE = 'https://atlas.example/travels/';
const NOW = new Date('2026-10-16T12:00:00.000Z');
const hash = text => createHash('sha256').update(text).digest('hex');
const assignment = (name, value) => `/* Generated by scripts/build-site.mjs. Edit content sources instead. */\nwindow.${name} = ${JSON.stringify(value)};\n`;

function fixture({ catalogAllAssets = false } = {}) {
  const data = { defaultJourneyId: 'first-trip', journeys: [
    { id: 'sample', kind: 'demo', published: true },
    { id: 'first-trip', kind: 'real', published: true, slug: 'first-trip.html' }
  ] };
  const photos = { 'first-trip': [{ id: 'p1', dayId: 'd1', src: 'https://private.invalid/protected/photo.webp' }] };
  const overrides = { photos: {}, days: {}, routes: {} };
  const files = {
    'journeys.js': assignment('JOURNEY_ATLAS_DATA', data),
    'trip-photos.js': assignment('JOURNEY_ATLAS_PHOTOS', photos),
    'content-overrides.js': assignment('JOURNEY_ATLAS_CONTENT_OVERRIDES', overrides)
  };
  const tags = () => Object.entries(files).map(([file, body]) => `<script src="./assets/${file}?v=${hash(body).slice(0, 12)}"></script>`);
  const pages = {
    '/travels/': `<!doctype html><html><body>${catalogAllAssets ? tags().join('') : tags()[0]}</body></html>`,
    '/travels/first-trip.html': `<!doctype html><html><body data-journey-id="first-trip">${tags().join('')}</body></html>`
  };
  const calls = [];
  const counts = new Map();
  const fetchImpl = async (url, init) => {
    const parsed = new URL(url);
    calls.push({ url, init });
    counts.set(parsed.pathname, (counts.get(parsed.pathname) ?? 0) + 1);
    if (fixtureFetch.onRequest) {
      const response = await fixtureFetch.onRequest(parsed, counts.get(parsed.pathname));
      if (response) return response;
    }
    const body = pages[parsed.pathname] ?? files[parsed.pathname.split('/').at(-1)];
    if (body === undefined) return new Response('missing', { status: 404 });
    return new Response(body, { headers: { 'Content-Type': parsed.pathname.endsWith('.js') ? 'application/javascript; charset=utf-8' : 'text/html; charset=utf-8' } });
  };
  const fixtureFetch = { data, photos, overrides, files, pages, calls, counts, fetchImpl };
  return fixtureFetch;
}

const capture = (input, site = SITE) => fetchPublicSnapshot(site, { fetchImpl: input.fetchImpl, now: () => NOW });

test('captures only coherent public metadata and records content-hash receipts', async () => {
  const f = fixture();
  const result = await capture(f, `${SITE}index.html`);
  assert.deepEqual(result.data, f.data);
  assert.deepEqual(result.photos, f.photos);
  assert.deepEqual(result.overrides, f.overrides);
  assert.equal(result.siteUrl, SITE);
  assert.equal(result.capturedAt, NOW.toISOString());
  assert.equal(result.source.kind, 'public-metadata');
  assert.equal(result.source.verification, 'versioned-public-metadata-only');
  assert.equal(result.source.journey.id, 'first-trip');
  assert.equal(result.source.catalog.sha256, hash(f.pages['/travels/']));
  assert.equal(result.source.assets.photos.sha256, hash(f.files['trip-photos.js']));
  assert.equal(result.source.assets.photos.version, hash(f.files['trip-photos.js']).slice(0, 12));
  assert.equal(f.calls.length, 10);
  assert.equal(new Set(f.calls.map(call => new URL(call.url).searchParams.get('_atlas_snapshot'))).size, 10);
  for (const { url, init } of f.calls) {
    assert.equal(new URL(url).origin, new URL(SITE).origin);
    assert.equal(init.redirect, 'error');
    assert.equal(init.credentials, 'omit');
    assert.equal(init.cache, 'no-store');
    assert.equal(init.headers['Cache-Control'], 'no-cache, no-store');
    assert.ok(init.signal instanceof AbortSignal);
    assert.doesNotMatch(url, /private\.invalid|photo-service|photo-auth/);
  }
  assert.doesNotMatch(JSON.stringify(result.source), /_atlas_snapshot|private\.invalid|protected/);
});

