test('rejects deployment races in HTML and assets on the verification pass', async () => {
  for (const path of ['/travels/', '/travels/first-trip.html', '/travels/assets/journeys.js', '/travels/assets/trip-photos.js', '/travels/assets/content-overrides.js']) {
    const f = fixture();
    f.onRequest = (url, count) => {
      if (url.pathname === path && count === 2) {
        if (path.endsWith('.js')) f.files[path.split('/').at(-1)] += '\n';
        else f.pages[path] += '\n';
      }
    };
    await assert.rejects(capture(f), /HTML changed during capture|content hash mismatch/);
  }
});

test('rejects non-JSON or appended executable assignments without running code', async () => {
  const attacks = [
    'window.JOURNEY_ATLAS_PHOTOS = (globalThis.__snapshotAttack = true, {});',
    'window.JOURNEY_ATLAS_PHOTOS = {}; globalThis.__snapshotAttack = true;',
    'window.JOURNEY_ATLAS_PHOTOS = JSON.parse("{}");',
    'window.JOURNEY_ATLAS_PHOTOS = {a: 1};',
    'window.JOURNEY_ATLAS_PHOTOS_EXTRA = {};',
    'window.JOURNEY_ATLAS_PHOTOS = [];',
    'window.JOURNEY_ATLAS_PHOTOS = null;',
    'window.JOURNEY_ATLAS_PHOTOS = {}',
    '/* attacker header */ window.JOURNEY_ATLAS_PHOTOS = {};'
  ];
  for (const attack of attacks) {
    const f = fixture();
    const previousVersion = hash(f.files['trip-photos.js']).slice(0, 12);
    f.files['trip-photos.js'] = attack;
    f.pages['/travels/first-trip.html'] = f.pages['/travels/first-trip.html'].replace(previousVersion, hash(attack).slice(0, 12));
    await assert.rejects(capture(f), /assignment|JSON object/);
    assert.equal(globalThis.__snapshotAttack, undefined);
  }
});

