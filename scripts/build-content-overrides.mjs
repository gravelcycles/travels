#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";

const photoPath = path.resolve("content/photo-overrides.json");
const routePath = path.resolve("content/route-overrides.json");
const dayPath = path.resolve("content/day-overrides.json");
const outputPath = path.resolve("dist/assets/content-overrides.js");

function readObject(filename) {
  const value = JSON.parse(fs.readFileSync(filename, "utf8"));
  if (!value || Array.isArray(value) || typeof value !== "object") {
    throw new Error(`${filename} must contain a JSON object`);
  }
  return value;
}

const overrides = {
  photos: readObject(photoPath),
  routes: readObject(routePath),
  days: readObject(dayPath)
};

const source = `/* Generated by scripts/build-content-overrides.mjs. */\nwindow.JOURNEY_ATLAS_CONTENT_OVERRIDES = ${JSON.stringify(overrides)};\n`;
fs.writeFileSync(outputPath, source);
console.log(`Wrote ${Object.keys(overrides.photos).length} photo, ${Object.keys(overrides.routes).length} route, and ${Object.keys(overrides.days).length} day overrides to ${outputPath}`);
